namespace AmznSellingPartner.Clients.Replenishment.Replenishment20221107
{
	using Newtonsoft.Json;
	using Newtonsoft.Json.Converters;

	using System.Runtime.Serialization;

	/// <summary>
	/// The metric name and description.
	/// </summary>
	[JsonConverter(typeof(StringEnumConverter))]
	public enum Metric
	{
		/// <summary>
		/// The number of units shipped to the subscribers over a period of time.
		/// </summary>
		[EnumMember(Value = "SHIPPED_SUBSCRIPTION_UNITS")]
		SHIPPED_SUBSCRIPTION_UNITS,

		/// <summary>
		/// The revenue generated from subscriptions over a period of time.
		/// </summary>
		[EnumMember(Value = "TOTAL_SUBSCRIPTIONS_REVENUE")]
		TOTAL_SUBSCRIPTIONS_REVENUE,

		/// <summary>
		/// The number of active subscriptions present at the end of the period.
		/// </summary>
		[EnumMember(Value = "ACTIVE_SUBSCRIPTIONS")]
		ACTIVE_SUBSCRIPTIONS,

		/// <summary>
		/// The percentage of items that were not shipped out of the total shipped units over a period of time due
		/// to being out of stock.
		/// </summary>
		[EnumMember(Value = "NOT_DELIVERED_DUE_TO_OOS")]
		NOT_DELIVERED_DUE_TO_OOS,

		/// <summary>
		/// The average revenue per subscriber and non-subscriber over the past 12 months for sellers and 6 months
		/// for vendors.
		/// </summary>
		[EnumMember(Value = "SUBSCRIBER_NON_SUBSCRIBER_AVERAGE_REVENUE")]
		SUBSCRIBER_NON_SUBSCRIBER_AVERAGE_REVENUE,

		/// <summary>
		/// The revenue that would have been generated had there not been out of stock.
		/// </summary>
		[EnumMember(Value = "LOST_REVENUE_DUE_TO_OOS")]
		LOST_REVENUE_DUE_TO_OOS,

		/// <summary>
		/// The average reorders per subscriber and non-subscriber over the last 12 months.
		/// </summary>
		[EnumMember(Value = "SUBSCRIBER_NON_SUBSCRIBER_AVERAGE_REORDERS")]
		SUBSCRIBER_NON_SUBSCRIBER_AVERAGE_REORDERS,

		/// <summary>
		/// The percentage of revenue from ASINs with coupons out of total revenue from all ASINs.
		/// </summary>
		[EnumMember(Value = "COUPONS_REVENUE_PENETRATION")]
		COUPONS_REVENUE_PENETRATION,

		/// <summary>
		/// The subscription revenue generated from subscriptions with over two deliveries, active subscriptions
		/// with one delivery and cancelled subscriptions after one delivery over the past 12 months.
		/// </summary>
		[EnumMember(Value = "REVENUE_BY_DELIVERIES")]
		REVENUE_BY_DELIVERIES,

		/// <summary>
		/// The percentage of subscriptions retained after 30 and 90 days of subscription creation.
		/// </summary>
		[EnumMember(Value = "SUBSCRIBER_RETENTION")]
		SUBSCRIBER_RETENTION,

		/// <summary>
		/// The percentage of subscription revenue generated by different tiers of seller-funded discount over the
		/// last 12 months.
		/// </summary>
		[EnumMember(Value = "REVENUE_PENETRATION_BY_SELLER_FUNDING")]
		REVENUE_PENETRATION_BY_SELLER_FUNDING,

		/// <summary>
		/// The percentage of new subscriptions acquired through coupons.
		/// </summary>
		[EnumMember(Value = "SHARE_OF_COUPON_SUBSCRIPTIONS")]
		SHARE_OF_COUPON_SUBSCRIPTIONS,
	}
}
