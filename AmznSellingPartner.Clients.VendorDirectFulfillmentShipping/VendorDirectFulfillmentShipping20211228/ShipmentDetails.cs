namespace AmznSellingPartner.Clients.VendorDirectFulfillmentShipping.VendorDirectFulfillmentShipping20211228
{
	using AmznSellingPartner.Clients.Attributes;

	using Newtonsoft.Json;

	using System;

	/// <summary>
	/// Details about a shipment
	/// </summary>
	public class ShipmentDetails : BaseClass
	{
		/// <summary>
		/// The date of the shipment's departure from vendor's location
		/// Vendors send ASNs within 30 minutes of departure from their warehouse/distribution center or six hours prior
		/// o the appointment time at the Amazon destination warehouse
		/// The shipped date mentioned in the shipment confirmation cannot be in the future
		/// </summary>
		[IsRequired]
		[JsonProperty("shippedDate")]
		public DateTime ShippedDate { get; set; }

		/// <summary>
		/// The shipment status
		/// </summary>
		[IsRequired]
		[JsonProperty("shipmentStatus")]
		public ShipmentStatus ShipmentStatus { get; set; }

		/// <summary>
		/// Provide the priority of the shipment
		/// </summary>
		[JsonProperty("isPriorityShipment")]
		public bool IsPriorityShipment { get; set; }

		/// <summary>
		/// The vendor order number is a unique identifier generated by a vendor for their reference
		/// </summary>
		[JsonProperty("vendorOrderNumber")]
		public string VendorOrderNumber { get; set; }

		/// <summary>
		/// The date on which the shipment is expected to reach the buyer's warehouse
		/// The date is estimated based on the average transit time between the ship-from location and the destination
		/// Usually, the exact appointment time is unknown when creating the shipment confirmation and is later provided
		/// y the buyer
		/// </summary>
		[JsonProperty("estimatedDeliveryDate")]
		public DateTime EstimatedDeliveryDate { get; set; }
	}
}
