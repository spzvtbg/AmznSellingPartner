namespace AmznSellingPartner.Clients.VendorInvoices.VendorInvoices
{
    using Newtonsoft.Json;

    /// <summary>
    /// References required in order to process a credit note. This information is required only if
    /// InvoiceType is CreditNote.
    /// </summary>
    public class CreditNoteDetails : BaseClass
    {
        /// <summary>
        /// Original Invoice Number when sending a credit note relating to an existing invoice. One Invoice
        /// only to be processed per Credit Note. This is mandatory for AP Credit Notes.
        /// </summary>
        [JsonProperty("referenceInvoiceNumber")]
        public string ReferenceInvoiceNumber { get; set; }

        /// <summary>
        /// Debit Note Number as generated by Amazon. Recommended for Returns and COOP Credit Notes.
        /// </summary>
        [JsonProperty("debitNoteNumber")]
        public string DebitNoteNumber { get; set; }

        /// <summary>
        /// Identifies the Returns Notice Number. Mandatory for all Returns Credit Notes.
        /// </summary>
        [JsonProperty("returnsReferenceNumber")]
        public string ReturnsReferenceNumber { get; set; }

        /// <summary>
        /// Date that a return is received by the vendor. It is mandatory for Returns Credit Note.
        /// </summary>
        [JsonProperty("goodsReturnDate")]
        public DateTime GoodsReturnDate { get; set; }

        /// <summary>
        /// Identifies the Returned Merchandise Authorization ID, if generated.
        /// </summary>
        [JsonProperty("rmaId")]
        public string RmaId { get; set; }

        /// <summary>
        /// Identifies the COOP reference used for COOP agreement. Failure to provide the COOP reference
        /// number or the Debit Note number may lead to a rejection of the Credit Note.
        /// </summary>
        [JsonProperty("coopReferenceNumber")]
        public string CoopReferenceNumber { get; set; }

        /// <summary>
        /// Identifies the consignor reference number (VRET number), if generated by Amazon.
        /// </summary>
        [JsonProperty("consignorsReferenceNumber")]
        public string ConsignorsReferenceNumber { get; set; }
    }
}
