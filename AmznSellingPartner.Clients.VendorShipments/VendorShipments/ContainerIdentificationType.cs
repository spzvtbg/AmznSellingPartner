namespace AmznSellingPartner.Clients.VendorShipments.VendorShipments
{
    using Newtonsoft.Json;
    using Newtonsoft.Json.Converters;

    using System.Runtime.Serialization;

    [JsonConverter(typeof(StringEnumConverter))]
    public enum ContainerIdentificationType
    {
        /// <summary>
        /// 2 Digit Application Identifier (00) followed by unique 18-digit Serial Shipment Container Code
        /// (SSCC) to be included to define a pallet/carton and to identify its contents.
        /// </summary>
        [EnumMember(Value = "SSCC")]
        SSCC,

        /// <summary>
        /// Amazon Container Code - a substitute for a SSCC that is generated by Amazon for small vendors
        /// and associated with a pallet/carton label.
        /// </summary>
        [EnumMember(Value = "AMZNCC")]
        AMZNCC,

        /// <summary>
        /// Global Trade Identification Number (part of the standard GS1 barcoding and product identification
        /// system).
        /// </summary>
        [EnumMember(Value = "GTIN")]
        GTIN,

        /// <summary>
        /// Barcode Packing Slip.
        /// </summary>
        [EnumMember(Value = "BPS")]
        BPS,

        /// <summary>
        /// Container identifier for import shipments.
        /// </summary>
        [EnumMember(Value = "CID")]
        CID,
    }
}
