namespace AmznSellingPartner.Clients.VendorShipments.VendorShipments
{
	using AmznSellingPartner.Clients.Attributes;

	using Newtonsoft.Json;

	using System;
	using System.Collections.Generic;

	/// <summary>
	/// A list of one or more shipments with respective details.
	/// </summary>
	public class Shipment : BaseClass
	{
		/// <summary>
		/// Unique Transportation ID created by Vendor (Should not be used over the last 365 days).
		/// </summary>
		[JsonProperty("vendorShipmentIdentifier")]
		[IsRequired]
		public string VendorShipmentIdentifier { get; set; } 

		/// <summary>
		/// Indicates the type of  transportation request such as (New,Cancel,Confirm and PackageLabelRequest). Each
		/// transactiontype has a unique set of operation and there are corresponding details to be populated for
		/// each operation.
		/// </summary>
		[JsonProperty("transactionType")]
		[IsRequired]
		public TransactionType TransactionType { get; set; } 

		/// <summary>
		/// The buyer Reference Number is a unique identifier generated by buyer for all Collect/WePay shipments
		/// when you submit a transportation request. This field is mandatory for Collect/WePay shipments.
		/// </summary>
		[JsonProperty("buyerReferenceNumber")]
		public string BuyerReferenceNumber { get; set; } 

		/// <summary>
		/// Date on which the transportation request was submitted.
		/// </summary>
		[JsonProperty("transactionDate")]
		[IsRequired]
		public DateTime TransactionDate { get; set; } 

		/// <summary>
		/// Indicates the current shipment status.
		/// </summary>
		[JsonProperty("currentShipmentStatus")]
		public CurrentShipmentStatus CurrentShipmentStatus { get; set; } 

		/// <summary>
		/// Date and time when the last status was updated.
		/// </summary>
		[JsonProperty("currentshipmentStatusDate")]
		public DateTime CurrentshipmentStatusDate { get; set; } 

		/// <summary>
		/// Indicates the list of current shipment status details and when the last update was received from carrier
		/// this is available on shipment Details response.
		/// </summary>
		[JsonProperty("shipmentStatusDetails")]
		public List<ShipmentStatusDetails> ShipmentStatusDetails { get; set; } 

		/// <summary>
		/// The date and time of the shipment request created by vendor.
		/// </summary>
		[JsonProperty("shipmentCreateDate")]
		public DateTime ShipmentCreateDate { get; set; } 

		/// <summary>
		/// The date and time of the departure of the shipment from the vendor's location. Vendors are requested
		/// to send ASNs within 30 minutes of departure from their warehouse/distribution center or at least 6 hours
		/// prior to the appointment time at the Buyer destination warehouse, whichever is sooner. Shipped date mentioned
		/// in the shipment confirmation should not be in the future.
		/// </summary>
		[JsonProperty("shipmentConfirmDate")]
		public DateTime ShipmentConfirmDate { get; set; } 

		/// <summary>
		/// The date and time of the package label created for the shipment by buyer.
		/// </summary>
		[JsonProperty("packageLabelCreateDate")]
		public DateTime PackageLabelCreateDate { get; set; } 

		/// <summary>
		/// Indicates if this transportation request is WePay/Collect or TheyPay/Prepaid. This is a mandatory in
		/// formation.
		/// </summary>
		[JsonProperty("shipmentFreightTerm")]
		public ShipmentFreightTerm ShipmentFreightTerm { get; set; } 

		/// <summary>
		/// Name/Address and tax details of the selling party.
		/// </summary>
		[JsonProperty("sellingParty")]
		[IsRequired]
		public PartyIdentification SellingParty { get; set; } 

		/// <summary>
		/// Name/Address and tax details of the ship from party.
		/// </summary>
		[JsonProperty("shipFromParty")]
		[IsRequired]
		public PartyIdentification ShipFromParty { get; set; } 

		/// <summary>
		/// Name/Address of the destination warehouse where the shipment is being shipped to.
		/// </summary>
		[JsonProperty("shipToParty")]
		[IsRequired]
		public PartyIdentification ShipToParty { get; set; } 

		/// <summary>
		/// Indicates the shipment measurement details on how many cartons and pallets and the total transportation
		/// weight and volume as part of this request. This is a mandatory detail which will help determining the
		/// transportation cost, truck allocations and route determination efficiently.
		/// </summary>
		[JsonProperty("shipmentMeasurements")]
		public TransportShipmentMeasurements ShipmentMeasurements { get; set; } 

		/// <summary>
		/// Indicates the earliest pickup date for the transportation from vendor warehouse. This information is
		/// mandatory to be filled for requesting transportation from Buyer (WePay/Collect).
		/// </summary>
		[JsonProperty("collectFreightPickupDetails")]
		public CollectFreightPickupDetails CollectFreightPickupDetails { get; set; } 

		/// <summary>
		/// Indicates the purchase orders involved for the transportation request. This group is an array create
		/// 1 for each PO and list their corresponding items. This information is used for deciding the route,truck
		/// allocation and storage efficiently. This is a mandatory information for Buyer performing transportation
		/// from vendor warehouse (WePay/Collect)
		/// </summary>
		[JsonProperty("purchaseOrders")]
		public List<PurchaseOrders> PurchaseOrders { get; set; } 

		/// <summary>
		/// Provide these fields only if this shipment is a direct import.
		/// </summary>
		[JsonProperty("importDetails")]
		public ImportDetails ImportDetails { get; set; } 

		/// <summary>
		/// A list of the items in this transportation and their associated inner container details. If any of the
		/// item detail fields are common at a carton or a pallet level, provide them at the corresponding carton
		/// or pallet level.
		/// </summary>
		[JsonProperty("containers")]
		public List<Containers> Containers { get; set; } 

		/// <summary>
		/// Transportation details this a mandatory information which states delivery date, shipping date and carrier
		/// details.
		/// </summary>
		[JsonProperty("transportationDetails")]
		public TransportationDetails TransportationDetails { get; set; } 
	}
}
