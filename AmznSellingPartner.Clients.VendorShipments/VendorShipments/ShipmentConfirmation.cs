namespace AmznSellingPartner.Clients.VendorShipments.VendorShipments
{
	using AmznSellingPartner.Clients.Attributes;

	using Newtonsoft.Json;

	using System;
	using System.Collections.Generic;

	/// <summary>
	/// A list of one or more shipment confirmations.
	/// </summary>
	public class ShipmentConfirmation : BaseClass
	{
		/// <summary>
		/// Unique shipment ID (not used over the last 365 days).
		/// </summary>
		[IsRequired]
		[JsonProperty("shipmentIdentifier")]
		public string ShipmentIdentifier { get; set; }

		/// <summary>
		/// Indicates if this shipment confirmation is the initial confirmation, or intended to replace an already
		/// posted shipment confirmation. If replacing an existing shipment confirmation, be sure to provide the
		/// identical shipmentIdentifier and sellingParty information as in the previous confirmation.
		/// </summary>
		[IsRequired]
		[JsonProperty("shipmentConfirmationType")]
		public ShipmentConfirmationType ShipmentConfirmationType { get; set; }

		/// <summary>
		/// The type of shipment.
		/// </summary>
		[JsonProperty("shipmentType")]
		public ShipmentType ShipmentType { get; set; }

		/// <summary>
		/// Shipment hierarchical structure.
		/// </summary>
		[JsonProperty("shipmentStructure")]
		public ShipmentStructure ShipmentStructure { get; set; }

		/// <summary>
		/// Transportation details for this shipment.
		/// </summary>
		[JsonProperty("transportationDetails")]
		public TransportationDetailsForShipmentConfirmation TransportationDetails { get; set; }

		/// <summary>
		/// The Amazon Reference Number is a unique identifier generated by Amazon for all Collect/WePay shipments
		/// when you submit  a routing request. This field is mandatory for Collect/WePay shipments.
		/// </summary>
		[JsonProperty("amazonReferenceNumber")]
		public string AmazonReferenceNumber { get; set; }

		/// <summary>
		/// Date on which the shipment confirmation was submitted.
		/// </summary>
		[IsRequired]
		[JsonProperty("shipmentConfirmationDate")]
		public DateTime ShipmentConfirmationDate { get; set; }

		/// <summary>
		/// The date and time of the departure of the shipment from the vendor's location. Vendors are requested
		/// to send ASNs within 30 minutes of departure from their warehouse/distribution center or at least 6 hours
		/// prior to the appointment time at the buyer destination warehouse, whichever is sooner. Shipped date mentioned
		/// in the shipment confirmation should not be in the future.
		/// </summary>
		[JsonProperty("shippedDate")]
		public DateTime ShippedDate { get; set; }

		/// <summary>
		/// The date and time on which the shipment is estimated to reach buyer's warehouse. It needs to be an estimate
		/// based on the average transit time between ship from location and the destination. The exact appointment
		/// time will be provided by the buyer and is potentially not known when creating the shipment confirmat
		/// ion.
		/// </summary>
		[JsonProperty("estimatedDeliveryDate")]
		public DateTime EstimatedDeliveryDate { get; set; }

		/// <summary>
		/// Name/Address and tax details of the selling party.
		/// </summary>
		[IsRequired]
		[JsonProperty("sellingParty")]
		public PartyIdentification SellingParty { get; set; }

		/// <summary>
		/// Name/Address and tax details of the ship from party.
		/// </summary>
		[IsRequired]
		[JsonProperty("shipFromParty")]
		public PartyIdentification ShipFromParty { get; set; }

		/// <summary>
		/// Name/Address of the destination warehouse where the shipment is being shipped to.
		/// </summary>
		[IsRequired]
		[JsonProperty("shipToParty")]
		public PartyIdentification ShipToParty { get; set; }

		[JsonProperty("shipmentMeasurements")]
		public ShipmentMeasurements ShipmentMeasurements { get; set; }

		/// <summary>
		/// Provide these fields only if this shipment is a direct import.
		/// </summary>
		[JsonProperty("importDetails")]
		public ImportDetails ImportDetails { get; set; }

		/// <summary>
		/// A list of the items in this shipment and their associated details. If any of the item detail fields are
		/// common at a carton or a pallet level, provide them at the corresponding carton or pallet level.
		/// </summary>
		[IsRequired]
		[JsonProperty("shippedItems")]
		public List<Item> ShippedItems { get; set; }

		/// <summary>
		/// A list of the cartons in this shipment.
		/// </summary>
		[JsonProperty("cartons")]
		public List<Carton> Cartons { get; set; }

		/// <summary>
		/// A list of the pallets in this shipment.
		/// </summary>
		[JsonProperty("pallets")]
		public List<Pallet> Pallets { get; set; }
	}
}
